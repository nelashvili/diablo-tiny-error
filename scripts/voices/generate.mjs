// Render every voiced line (src/game/voiceCast.ts) with Kokoro TTS into public/assets/audio/voice/<key>.m4a
// and list them in src/audio/voiceLines.gen.ts. Only new or changed lines are rendered.
//
// Setup once:   npm --prefix scripts/voices install
// Run:          node scripts/voices/generate.mjs [--force] [--only <key prefix>]
// Needs macOS `afconvert` (built in) or `ffmpeg` to encode AAC. Kokoro-82M is Apache-2.0.
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';
import { KokoroTTS } from 'kokoro-js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const OUT = path.join(ROOT, 'public/assets/audio/voice');
const INDEX = path.join(ROOT, 'src/audio/voiceLines.gen.ts');
const MODEL = 'onnx-community/Kokoro-82M-v1.0-ONNX';

const args = process.argv.slice(2);
const force = args.includes('--force');
const only = args.includes('--only') ? args[args.indexOf('--only') + 1] : undefined;

// Load the game's own data through Vite (aliases, import.meta.glob).
const vite = await createServer({
  root: ROOT,
  configFile: path.join(ROOT, 'vite.config.ts'),
  server: { middlewareMode: true, hmr: false },
  appType: 'custom',
  logLevel: 'error',
});
let script;
try {
  const { DB } = await vite.ssrLoadModule('/src/data/db.ts');
  const { nameEntries } = await vite.ssrLoadModule('/src/data/names.ts');
  const { voiceScript } = await vite.ssrLoadModule('/src/game/voiceCast.ts');
  script = voiceScript(nameEntries(), DB.quests);
} finally {
  await vite.close();
}

const hashOf = (line) =>
  createHash('sha1')
    .update(JSON.stringify([line.text, line.cast]))
    .digest('hex')
    .slice(0, 10);
const previous = fs.existsSync(INDEX)
  ? Object.fromEntries(
      [...fs.readFileSync(INDEX, 'utf8').matchAll(/'([^']+)': '([0-9a-f]+)'/g)].map((m) => [m[1], m[2]]),
    )
  : {};

fs.mkdirSync(OUT, { recursive: true });
const fileOf = (key) => path.join(OUT, `${key}.m4a`);
const todo = script.filter(
  (l) =>
    (!only || l.key.startsWith(only)) &&
    (force || previous[l.key] !== hashOf(l) || !fs.existsSync(fileOf(l.key))),
);
console.log(`${script.length} lines, ${todo.length} to render`);

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'dte-voice-'));
if (todo.length > 0) {
  const tts = await KokoroTTS.from_pretrained(MODEL, { dtype: 'q8', device: 'cpu' });
  for (const [i, line] of todo.entries()) {
    const { voice, speed = 1, pitch = 1 } = line.cast;
    // Speak faster by `pitch`, then resample tape-style: pitch shifts, tempo returns to `speed`.
    const audio = await tts.generate(line.text, { voice, speed: speed / pitch });
    const samples = finish(resample(audio.audio, pitch), audio.sampling_rate);
    const wav = path.join(tmp, 'line.wav');
    fs.writeFileSync(wav, toWav(samples, audio.sampling_rate));
    encode(wav, fileOf(line.key));
    console.log(
      `[${i + 1}/${todo.length}] ${line.key} (${(samples.length / audio.sampling_rate).toFixed(1)}s)`,
    );
  }
}
fs.rmSync(tmp, { recursive: true, force: true });

// Drop files for lines that no longer exist, then write the index.
const keep = new Set(script.map((l) => `${l.key}.m4a`));
for (const f of fs.readdirSync(OUT)) if (!keep.has(f)) fs.rmSync(path.join(OUT, f));
const rows = script.map((l) => `  '${l.key}': '${hashOf(l)}',`).join('\n');
fs.writeFileSync(
  INDEX,
  `/** GENERATED by scripts/voices/generate.mjs. Do not edit. Voiced line key → content hash. */\n` +
    `const VOICE_LINES: Record<string, string> = {\n${rows}\n};\nexport default VOICE_LINES;\n`,
);
console.log(`wrote ${path.relative(ROOT, INDEX)}`);

// License manifest: replace this pack's entries (every asset file must be listed; see catalog.test.ts).
const MANIFEST = path.join(ROOT, 'assets/manifest.json');
const manifest = JSON.parse(fs.readFileSync(MANIFEST, 'utf8'));
const voiceEntries = script.map((l) => ({
  path: `public/assets/audio/voice/${l.key}.m4a`,
  bytes: fs.statSync(fileOf(l.key)).size,
  source: 'scripts/voices/generate.mjs (this repository)',
  pack: 'Diablo Tiny Error voice lines',
  author: 'Diablo Tiny Error project (generated)',
  license: 'CC0-1.0',
  licenseUrl: 'https://creativecommons.org/publicdomain/zero/1.0/',
  homepage: 'https://huggingface.co/hexgrad/Kokoro-82M',
  repo: '',
  licenseNote:
    'Original lines spoken by the Kokoro-82M TTS model (Apache-2.0, outputs unrestricted); dedicated to the public domain (CC0)',
  modifications: 'generated, pitch-shifted, encoded as AAC',
}));
manifest.assets = [
  ...manifest.assets.filter((a) => !a.path.startsWith('public/assets/audio/voice/')),
  ...voiceEntries,
].sort((a, b) => a.path.localeCompare(b.path));
fs.writeFileSync(MANIFEST, JSON.stringify(manifest, null, 2) + '\n');
console.log(`updated ${path.relative(ROOT, MANIFEST)} (${voiceEntries.length} voice files)`);

/** Linear-interpolation resample: playing `factor`× faster (pitch up when > 1). */
function resample(x, factor) {
  if (factor === 1) return x;
  const n = Math.floor(x.length / factor);
  const y = new Float32Array(n);
  for (let i = 0; i < n; i++) {
    const p = i * factor;
    const j = Math.floor(p);
    const f = p - j;
    y[i] = (x[j] ?? 0) * (1 - f) + (x[j + 1] ?? 0) * f;
  }
  return y;
}

/** Trim silence (keeping 80 ms), even out loudness (RMS target, peak-capped). */
function finish(x, sr) {
  const thr = 0.01;
  let a = 0;
  let b = x.length - 1;
  while (a < b && Math.abs(x[a]) < thr) a++;
  while (b > a && Math.abs(x[b]) < thr) b--;
  const pad = Math.floor(sr * 0.08);
  const y = x.slice(Math.max(0, a - pad), Math.min(x.length, b + pad));
  let sum = 0;
  let peak = 0;
  for (const v of y) {
    sum += v * v;
    peak = Math.max(peak, Math.abs(v));
  }
  const rms = Math.sqrt(sum / Math.max(1, y.length));
  const k = Math.min(0.12 / Math.max(rms, 1e-6), 0.95 / Math.max(peak, 1e-6));
  for (let i = 0; i < y.length; i++) y[i] *= k;
  return y;
}

function toWav(x, sr) {
  const b = Buffer.alloc(44 + x.length * 2);
  b.write('RIFF', 0);
  b.writeUInt32LE(36 + x.length * 2, 4);
  b.write('WAVEfmt ', 8);
  b.writeUInt32LE(16, 16);
  b.writeUInt16LE(1, 20);
  b.writeUInt16LE(1, 22);
  b.writeUInt32LE(sr, 24);
  b.writeUInt32LE(sr * 2, 28);
  b.writeUInt16LE(2, 32);
  b.writeUInt16LE(16, 34);
  b.write('data', 36);
  b.writeUInt32LE(x.length * 2, 40);
  for (let i = 0; i < x.length; i++)
    b.writeInt16LE(Math.round(Math.max(-1, Math.min(1, x[i])) * 32767), 44 + i * 2);
  return b;
}

function encode(wav, out) {
  try {
    execFileSync('afconvert', ['-f', 'm4af', '-d', 'aac', '-b', '40000', wav, out]);
  } catch {
    execFileSync('ffmpeg', ['-v', 'error', '-y', '-i', wav, '-c:a', 'aac', '-b:a', '40k', out]);
  }
}
